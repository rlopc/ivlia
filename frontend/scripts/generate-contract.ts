// Generates src/contract/ from the backend's JSON Schema of the events:
// TypeScript types (json-schema-to-typescript) and a standalone Ajv validator.
// With --check, it writes nothing and fails if the versioned files differ.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { Ajv2020 } from "ajv/dist/2020.js";
// CommonJS: under nodenext the default import is the module object.
import standalone from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(import.meta.dirname, "..");
const schemaFile = path.resolve(root, "../backend/schemas/events.schema.json");
const contractDir = path.join(root, "src/contract");
const banner =
  "// Generated by frontend/scripts/generate-contract.ts from\n" +
  "// backend/schemas/events.schema.json. Do not edit: run `just contract`.\n";

interface EventsSchema {
  type?: "object";
  discriminator: { propertyName: string; mapping?: unknown };
  $defs: Record<string, { properties: Record<string, { title?: string }> }>;
}

async function generate(): Promise<Map<string, string>> {
  const schema = JSON.parse(await readFile(schemaFile, "utf8")) as EventsSchema;
  // Ajv's discriminator does not support `mapping`, and its strict mode
  // wants the type of the object that holds the discriminator.
  delete schema.discriminator.mapping;
  schema.type = "object";
  // Property titles would become one type alias per field.
  for (const definition of Object.values(schema.$defs)) {
    for (const property of Object.values(definition.properties)) {
      delete property.title;
    }
  }

  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    discriminator: true,
  });
  const validator = standalone.default(ajv, ajv.compile(schema));
  // The types do not list unknown fields; the validator still accepts them.
  const types = await compile(schema, "ApiEvent", {
    bannerComment: "",
    additionalProperties: false,
  });
  const declaration = [
    'import type { ErrorObject } from "ajv";',
    'import type { ApiEvent } from "./events.ts";',
    "",
    "declare const validateEvent: ((data: unknown) => data is ApiEvent) & {",
    "  errors?: ErrorObject[] | null;",
    "};",
    "export default validateEvent;",
    "",
  ].join("\n");

  return new Map([
    ["events.ts", banner + "\n" + types],
    ["validate-event.js", banner + validator + "\n"],
    ["validate-event.d.ts", banner + "\n" + declaration],
  ]);
}

const files = await generate();
if (process.argv.includes("--check")) {
  const stale: string[] = [];
  for (const [name, content] of files) {
    const current = await readFile(path.join(contractDir, name), "utf8").catch(
      () => null,
    );
    if (current !== content) stale.push(name);
  }
  if (stale.length > 0) {
    console.error(
      `src/contract/ is out of date (${stale.join(", ")}). Run \`just contract\`.`,
    );
    process.exit(1);
  }
} else {
  // Everything is generated before anything is written.
  await mkdir(contractDir, { recursive: true });
  for (const [name, content] of files) {
    await writeFile(path.join(contractDir, name), content);
  }
}
