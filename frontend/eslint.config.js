import js from "@eslint/js";
import boundaries from "eslint-plugin-boundaries";
import reactHooks from "eslint-plugin-react-hooks";
import { defineConfig, globalIgnores } from "eslint/config";
import globals from "globals";
import tseslint from "typescript-eslint";

// Each folder of src/ is an element; the policies say who may import whom.
const elements = [
  { type: "app", pattern: "src/app" },
  { type: "contract", pattern: "src/contract" },
  { type: "api", pattern: "src/api" },
  { type: "shared", pattern: "src/shared" },
  { type: "ui", pattern: "src/components/ui" },
  // More specific first: a file belongs to the first element that matches.
  { type: "model", pattern: "src/features/*/model", capture: ["feature"] },
  { type: "adapter", pattern: "src/features/*/adapter", capture: ["feature"] },
  { type: "feature", pattern: "src/features/*", capture: ["feature"] },
];

const sameFeature = {
  captured: { feature: "{{ from.element.captured.feature }}" },
};

const policies = [
  // Local elements (the default is to disallow).
  {
    from: { element: { type: "app" } },
    allow: {
      to: {
        element: { types: ["feature", "shared", "ui", "api", "contract"] },
      },
    },
  },
  {
    from: { element: { type: "feature" } },
    allow: [
      {
        to: {
          element: { types: ["feature", "adapter", "model"], ...sameFeature },
        },
      },
      { to: { element: { types: ["shared", "ui", "api", "contract"] } } },
    ],
  },
  {
    from: { element: { type: "adapter" } },
    allow: [
      { to: { element: { type: "model", ...sameFeature } } },
      { to: { element: { types: ["shared", "ui", "api", "contract"] } } },
    ],
  },
  // Pure logic: only the contract and its own feature's model.
  {
    from: { element: { type: "model" } },
    allow: { to: { element: { type: "model", ...sameFeature } } },
  },
  {
    from: { element: { type: "model" } },
    allow: { to: { element: { type: "contract" } } },
  },
  {
    from: { element: { type: "api" } },
    allow: { to: { element: { type: "contract" } } },
  },
  {
    from: { element: { types: ["shared", "ui"] } },
    allow: { to: { element: { types: ["shared", "ui"] } } },
  },

  // External packages: all allowed, except these. The last match wins.
  { allow: { to: { module: { origin: ["external", "core"] } } } },
  {
    disallow: {
      to: { module: { origin: "external", source: "@assistant-ui/*" } },
    },
    message:
      "Only the chat adapter (features/chat/adapter) imports assistant-ui",
  },
  {
    from: { element: { type: "adapter", captured: { feature: "chat" } } },
    allow: {
      to: { module: { origin: "external", source: "@assistant-ui/*" } },
    },
  },
  {
    from: { element: { type: "model" } },
    disallow: {
      to: {
        module: { origin: "external", source: ["react", "react-*", "react/*"] },
      },
    },
    message: "A feature model is pure logic: no React",
  },
];

export default defineConfig([
  // Generated code and build output.
  globalIgnores([
    "dist",
    "src/contract",
    "coverage",
    "playwright-report",
    "test-results",
  ]),
  {
    files: ["**/*.{ts,tsx}"],
    extends: [js.configs.recommended, tseslint.configs.strictTypeChecked],
    languageOptions: {
      globals: globals.browser,
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
  },
  {
    files: ["src/**/*.{ts,tsx}"],
    extends: [reactHooks.configs.flat.recommended],
    plugins: { boundaries },
    settings: {
      "import/resolver": { typescript: { alwaysTryTypes: true } },
      "boundaries/elements": elements,
    },
    rules: {
      "boundaries/dependencies": [
        2,
        { default: "disallow", checkAllOrigins: true, policies },
      ],
    },
  },
  // shadcn components: generated by its CLI, so only the basic rules apply.
  {
    files: ["src/components/ui/**"],
    extends: [tseslint.configs.disableTypeChecked],
  },
  {
    files: ["scripts/**", "*.config.ts"],
    languageOptions: { globals: globals.node },
  },
]);
